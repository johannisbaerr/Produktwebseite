alter table public.products
  add column if not exists customizable boolean not null default false;

create table if not exists public.extras (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 160),
  price_cents integer not null check (price_cents >= 0),
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_extras (
  product_id bigint not null references public.products(id) on delete cascade,
  extra_id bigint not null references public.extras(id) on delete cascade,
  primary key (product_id, extra_id)
);

create index if not exists product_extras_extra_id_idx on public.product_extras(extra_id);

alter table public.extras enable row level security;
alter table public.product_extras enable row level security;

revoke all on public.extras, public.product_extras from anon, authenticated;
grant all on public.extras, public.product_extras to service_role;
grant usage, select on sequence public.extras_id_seq to service_role;

create or replace function public.set_product_extras(
  target_product_id bigint,
  target_extra_ids bigint[],
  enable_customization boolean
)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  selected_ids bigint[] := coalesce(target_extra_ids, '{}'::bigint[]);
begin
  if cardinality(selected_ids) <> (select count(distinct selected_id) from unnest(selected_ids) as selected(selected_id)) then
    return 'invalid_extras';
  end if;

  if cardinality(selected_ids) > 0 and exists (
    select 1
      from unnest(selected_ids) as selected(selected_id)
      left join public.extras on extras.id = selected.selected_id
     where extras.id is null
  ) then
    return 'invalid_extras';
  end if;

  update public.products
     set customizable = enable_customization
   where id = target_product_id;

  if not found then
    return 'product_missing';
  end if;

  delete from public.product_extras where product_id = target_product_id;

  if cardinality(selected_ids) > 0 then
    insert into public.product_extras (product_id, extra_id)
    select target_product_id, selected_id
      from unnest(selected_ids) as selected(selected_id);
  end if;

  return 'saved';
end;
$$;

revoke all on function public.set_product_extras(bigint, bigint[], boolean) from public, anon, authenticated;
grant execute on function public.set_product_extras(bigint, bigint[], boolean) to service_role;

create or replace function public.fulfill_order(order_token text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  saved_order public.orders%rowtype;
  order_product record;
  order_extra record;
  current_stock integer;
begin
  select * into saved_order from public.orders where token = order_token for update;

  if not found then return 'not_found'; end if;
  if saved_order.fulfilled_at is not null then return 'already_fulfilled'; end if;
  if jsonb_typeof(saved_order.items) <> 'array' or jsonb_array_length(saved_order.items) = 0 then return 'invalid_order'; end if;

  if exists (
    select 1 from jsonb_array_elements(saved_order.items) as order_items(value)
    where jsonb_typeof(value) <> 'object'
       or coalesce(value ->> 'productId', '') !~ '^[1-9][0-9]*$'
       or coalesce(value ->> 'quantity', '') !~ '^[1-9][0-9]*$'
       or (value ? 'extras' and jsonb_typeof(value -> 'extras') <> 'array')
  ) then return 'invalid_order'; end if;

  if exists (
    select 1
      from jsonb_array_elements(saved_order.items) as order_items(value)
      cross join lateral jsonb_array_elements(coalesce(value -> 'extras', '[]'::jsonb)) as selected_extra(extra)
     where jsonb_typeof(selected_extra.extra) <> 'object'
        or coalesce(selected_extra.extra ->> 'id', '') !~ '^[1-9][0-9]*$'
        or coalesce(selected_extra.extra ->> 'name', '') = ''
        or coalesce(selected_extra.extra ->> 'priceCents', '') !~ '^(0|[1-9][0-9]*)$'
  ) then return 'invalid_order'; end if;

  for order_product in
    select (value ->> 'productId')::bigint as product_id, sum((value ->> 'quantity')::integer)::integer as quantity
      from jsonb_array_elements(saved_order.items) as order_items(value)
     group by (value ->> 'productId')::bigint
     order by (value ->> 'productId')::bigint
  loop
    select stock into current_stock from public.products where id = order_product.product_id for update;
    if not found then return 'product_missing'; end if;
    if current_stock is null or current_stock < order_product.quantity then return 'insufficient_stock'; end if;
  end loop;

  for order_extra in
    select (selected_extra.extra ->> 'id')::bigint as extra_id,
           sum((order_item.value ->> 'quantity')::integer)::integer as quantity
      from jsonb_array_elements(saved_order.items) as order_item(value)
      cross join lateral jsonb_array_elements(coalesce(order_item.value -> 'extras', '[]'::jsonb)) as selected_extra(extra)
     group by (selected_extra.extra ->> 'id')::bigint
     order by (selected_extra.extra ->> 'id')::bigint
  loop
    select stock into current_stock from public.extras where id = order_extra.extra_id for update;
    if not found then return 'extra_missing'; end if;
    if current_stock is null or current_stock < order_extra.quantity then return 'insufficient_extra_stock'; end if;
  end loop;

  update public.products as product
     set stock = product.stock - ordered_product.quantity
    from (
      select (value ->> 'productId')::bigint as product_id, sum((value ->> 'quantity')::integer)::integer as quantity
        from jsonb_array_elements(saved_order.items) as order_items(value)
       group by (value ->> 'productId')::bigint
    ) as ordered_product
   where product.id = ordered_product.product_id;

  update public.extras as extra
     set stock = extra.stock - ordered_extra.quantity,
         updated_at = now()
    from (
      select (selected_extra.extra ->> 'id')::bigint as extra_id,
             sum((order_item.value ->> 'quantity')::integer)::integer as quantity
        from jsonb_array_elements(saved_order.items) as order_item(value)
        cross join lateral jsonb_array_elements(coalesce(order_item.value -> 'extras', '[]'::jsonb)) as selected_extra(extra)
       group by (selected_extra.extra ->> 'id')::bigint
    ) as ordered_extra
   where extra.id = ordered_extra.extra_id;

  update public.orders set fulfilled_at = now() where token = order_token;
  return 'fulfilled';
end;
$$;

revoke all on function public.fulfill_order(text) from public, anon, authenticated;
grant execute on function public.fulfill_order(text) to service_role;
